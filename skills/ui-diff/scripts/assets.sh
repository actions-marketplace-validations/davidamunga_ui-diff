# Shared by publish.sh and prune.sh (sourced, not run). The assets branch is edited in a
# throwaway clone and always pushed as one parentless commit with --force-with-lease, so
# the user's checkout is never touched and concurrent writers fail instead of erasing
# each other's images.
#
#   UI_DIFF_BRANCH=name     branch to use (default ui-diff-assets)
#   UI_DIFF_REMOTE=url      remote to use instead of this checkout's origin (no checkout needed)
#   UI_DIFF_REPO=owner/repo overrides the repo parsed from the remote URL (and skips gh checks)
#   UI_DIFF_GIT_TOKEN=tok   authenticate git over https with this token (CI; see action.yml)

BRANCH="${UI_DIFF_BRANCH:-ui-diff-assets}"
REMOTE_URL="${UI_DIFF_REMOTE:-$(git remote get-url origin)}"
# owner/repo from the remote URL (https or ssh).
REPO="${UI_DIFF_REPO:-$(echo "$REMOTE_URL" | sed -E 's#^.*github\.com[:/]##; s#\.git$##')}"

# Exit 3 when gh says we can't push (e.g. a PR from a fork). Skipped when UI_DIFF_REPO is set.
assets_check_access() {
  [ -z "${UI_DIFF_REPO:-}" ] || return 0
  INFO="$(gh repo view "$REPO" --json viewerPermission,visibility -q '.viewerPermission + " " + .visibility' 2>/dev/null || true)"
  case "$INFO" in
    ADMIN*|MAINTAIN*|WRITE*) ;;
    "") echo "warning: couldn't check repo permissions with gh; trying anyway" >&2 ;;
    *) echo "no push access to $REPO (${INFO%% *}); use manual mode instead" >&2; exit 3 ;;
  esac
}

# cd into a fresh clone holding the branch's current tree (empty if the branch is new).
# Sets TMP and LEASE (the branch's current sha, "" if it doesn't exist yet).
assets_clone() {
  TMP="$(mktemp -d)"
  trap 'rm -rf "$TMP"' EXIT
  cd "$TMP"
  git init -q
  git remote add origin "$REMOTE_URL"
  if [ -n "${UI_DIFF_GIT_TOKEN:-}" ]; then
    git config http.extraheader "AUTHORIZATION: basic $(printf 'x-access-token:%s' "$UI_DIFF_GIT_TOKEN" | base64 | tr -d '\n')"
  fi
  LEASE=""
  if OLD="$(git ls-remote --exit-code --heads origin "$BRANCH" 2>/dev/null | cut -f1)"; then
    git fetch -q --depth 1 origin "$BRANCH"
    git checkout -q FETCH_HEAD
    LEASE="$OLD"
  fi
}

# Replace the branch with one commit holding the current tree.
assets_push() {
  [ -f README.md ] || printf '# UI diff assets\n\nScreenshots generated by the ui-diff skill for PR reviews. Safe to delete.\n' > README.md
  git checkout -q --orphan publish
  git add -A
  git -c user.name="ui-diff" -c user.email="ui-diff@users.noreply.github.com" commit -q -m "$1" >/dev/null
  if ! git push -q --force-with-lease="refs/heads/$BRANCH:$LEASE" origin "publish:refs/heads/$BRANCH"; then
    echo "push rejected (someone published at the same time, or no write access) — rerun" >&2
    exit 1
  fi
}
