#!/usr/bin/env bash
# Push a report bundle's images to an assets branch so they can be embedded in PR
# comments/descriptions. GitHub renders them inline, in private repos too (for anyone
# who can read the repo).
#
# Usage: publish.sh <report-dir> <pr-number> [head-sha]
# Prints the URL prefix on stdout; an image's URL is "<prefix>/<relative path>?raw=true".
#
#   UI_DIFF_BRANCH=name   branch to use (default ui-diff-assets)
#   UI_DIFF_PRUNE=1       also delete images of PRs that are no longer open
#
# Exit codes: 3 = no push access (e.g. PR from a fork) → use manual mode.
#
# The branch is kept as a single commit (each publish replaces it), so `git clone`, which
# fetches every branch, only ever downloads the images that are currently referenced.
# Works in a throwaway clone; the user's checkout is never touched.
set -euo pipefail

REPORT="$(cd "$1" && pwd)"
PR="$2"
SHA="${3:-$(git rev-parse --short HEAD)}"
BRANCH="${UI_DIFF_BRANCH:-ui-diff-assets}"
REMOTE_URL="$(git remote get-url origin)"
# owner/repo from the remote URL (https or ssh); UI_DIFF_REPO overrides (and skips gh checks).
REPO="${UI_DIFF_REPO:-$(echo "$REMOTE_URL" | sed -E 's#^.*github\.com[:/]##; s#\.git$##')}"
DEST="pr-$PR/$SHA"

if [ -z "${UI_DIFF_REPO:-}" ]; then
  INFO="$(gh repo view "$REPO" --json viewerPermission,visibility -q '.viewerPermission + " " + .visibility' 2>/dev/null || true)"
  case "$INFO" in
    ADMIN*|MAINTAIN*|WRITE*) ;;
    "") echo "warning: couldn't check repo permissions with gh; trying anyway" >&2 ;;
    *) echo "no push access to $REPO (${INFO%% *}); use manual mode instead" >&2; exit 3 ;;
  esac
  [ "${INFO##* }" = "PUBLIC" ] && echo "note: $REPO is public, so these screenshots will be publicly visible" >&2
fi

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
cd "$TMP"
git init -q
git remote add origin "$REMOTE_URL"
LEASE=""
if OLD="$(git ls-remote --exit-code --heads origin "$BRANCH" 2>/dev/null | cut -f1)"; then
  git fetch -q --depth 1 origin "$BRANCH"
  git checkout -q FETCH_HEAD
  LEASE="$OLD"
fi

if [ "${UI_DIFF_PRUNE:-}" = 1 ] && [ -z "${UI_DIFF_REPO:-}" ]; then
  OPEN=" $(gh pr list --repo "$REPO" --state open --limit 1000 --json number -q '.[].number' | tr '\n' ' ') "
  for d in pr-*; do
    [ -d "$d" ] || continue
    n="${d#pr-}"
    [[ "$OPEN" == *" $n "* ]] || [ "$n" = "$PR" ] || { rm -rf "$d"; echo "pruned $d" >&2; }
  done
fi

# Images only; results.json etc. stay local. Older SHAs of this PR are kept so earlier
# comments/edits don't show broken images.
rm -rf "$DEST"
mkdir -p "$DEST"
(cd "$REPORT" && find . -name '*.png' -print0 | xargs -0 -I{} rsync -R {} "$TMP/$DEST/")
[ -f README.md ] || printf '# UI diff assets\n\nScreenshots generated by the ui-diff skill for PR reviews. Safe to delete.\n' > README.md

# Fresh parentless commit holding the current tree.
git checkout -q --orphan publish
git add -A
git -c user.name="ui-diff" -c user.email="ui-diff@users.noreply.github.com" \
  commit -q -m "ui-diff assets (latest: PR #$PR @ $SHA)" >/dev/null
# --force-with-lease: if someone else published since we fetched, fail instead of erasing their images.
if ! git push -q --force-with-lease="refs/heads/$BRANCH:$LEASE" origin "publish:refs/heads/$BRANCH"; then
  echo "push rejected (someone published at the same time?) — rerun" >&2
  exit 1
fi

echo "https://github.com/$REPO/blob/$BRANCH/$DEST"
